def soma(a, b):
    print(f"somando {a} e {b}")
    return a + b

def multiplica(a, b):
    print(f"multiplicando {a} e {b}")
    return a * b

def media(lista):

    print(f"calculando media com base em {lista}")
    return round(sum(lista) / len(lista), 2)


def divisao(a, b):
    print(f"dividindo {a} e {b}")
    return a / b


